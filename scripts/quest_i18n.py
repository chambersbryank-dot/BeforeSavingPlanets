def apply(COPY):
    base_keys = set(COPY["en"])
    for lang, overlay in OVER.items():
        merged = dict(COPY["en"])
        merged.update(overlay)
        missing = base_keys - set(merged)
        if missing:
            raise SystemExit(lang + " dropped " + ",".join(sorted(missing)[:8]))
        COPY[lang] = merged
    for lang in ("es","it","ar","he"):
        if lang not in COPY:
            COPY[lang] = dict(COPY["en"])

